/** -1, 0 or 1, comparing versions like 6.0.0 and 5.17.2. */
export function compareVersions(a, b) {
  // Numbers part by part; a pre-release (11.0.0-beta.2) comes before its release (11.0.0), betas in their order.
  const split = (v) => {
    const [core, pre] = String(v).split(/-(.*)/s);
    return { core: core.split('.').map((x) => Number(x) || 0), pre: pre ? pre.split('.').map((x) => Number(x) || 0) : null };
  };
  const x = split(a);
  const y = split(b);
  for (let i = 0; i < Math.max(x.core.length, y.core.length); i++) {
    if ((x.core[i] ?? 0) !== (y.core[i] ?? 0)) return (x.core[i] ?? 0) < (y.core[i] ?? 0) ? -1 : 1;
  }
  if (!x.pre || !y.pre) return x.pre ? -1 : y.pre ? 1 : 0;
  for (let i = 0; i < Math.max(x.pre.length, y.pre.length); i++) {
    if ((x.pre[i] ?? 0) !== (y.pre[i] ?? 0)) return (x.pre[i] ?? 0) < (y.pre[i] ?? 0) ? -1 : 1;
  }
  return 0;
}
